struct ExerciseAttribute {
    var upAngle : Double
    var downAngle : Double
    var repetition : Int
    var timeUp : Double
    var timeDown : Double
}

var curl : ExerciseAttribute = ExerciseAttribute(upAngle: 135, downAngle: 65, repetition: 8, timeUp: 10, timeDown: 10)
var hammer : ExerciseAttribute = ExerciseAttribute(upAngle: 10, downAngle: 10, repetition: 10, timeUp: 10, timeDown: 10)
var raise : ExerciseAttribute = ExerciseAttribute(upAngle: 10, downAngle: 10, repetition: 10, timeUp: 10, timeDown: 10)



